/**
 * Finds the core's component token sets: every `*-tokens.ts` file under `src`, sorted by
 * path, and each set it exports. There is no hand-kept list, so a component adds its tokens
 * by adding its own file.
 */
import { readdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  componentTokenList,
  componentTokensCss,
  isComponentTokenSet,
  type ComponentTokenSet,
} from '../../src/tokens/component';

const SRC = fileURLToPath(new URL('../../src/', import.meta.url));

/** The core's sets are M3 component tokens, so their private prefix is `md-comp-`. */
const SET_NAME = /^md-comp-[a-z0-9]+(-[a-z0-9]+)*$/;

export interface DiscoveredTokenSet {
  /** The file, relative to `src`. */
  file: string;
  /** The export's name: `cardTokenSet`. */
  exportName: string;
  set: ComponentTokenSet;
}

export async function discoverComponentTokenSets(): Promise<DiscoveredTokenSet[]> {
  const files = (await readdir(SRC, { recursive: true }))
    .filter((file) => /-tokens\.ts$/.test(file))
    .sort();
  const found: DiscoveredTokenSet[] = [];
  for (const file of files) {
    const module = (await import(pathToFileURL(`${SRC}${file}`).href)) as Record<string, unknown>;
    for (const [exportName, value] of Object.entries(module)) {
      if (!isComponentTokenSet(value)) continue;
      if (!SET_NAME.test(value.name)) {
        throw new Error(`${file}: ${exportName} is named "${value.name}", not md-comp-<component>`);
      }
      found.push({ file, exportName, set: value });
    }
  }
  const names = found.map(({ set }) => set.name);
  const repeated = names.filter((name, index) => names.indexOf(name) !== index);
  if (repeated.length > 0) throw new Error(`Two token sets are named ${repeated.join(', ')}`);
  return found;
}

/** `components.css`: every set's private variables, in discovery order. */
export function componentsCss(sets: readonly DiscoveredTokenSet[]): string {
  return sets.map(({ set }) => componentTokensCss(set)).join('\n\n');
}

/**
 * `component-tokens.txt`: every public variable, sorted. It's checked in, so a pull request
 * shows each name it adds, and a test fails if a name disappears (names are public API).
 */
export function componentTokenNames(sets: readonly DiscoveredTokenSet[]): string {
  const names = sets.flatMap(({ set }) => componentTokenList(set).map(({ name }) => name)).sort();
  return [
    '# The public component tokens of @windmorph/react, one per line. Generated by',
    '# `pnpm generate` from the `*-tokens.ts` files; a test fails when it is out of date.',
    ...names,
  ].join('\n');
}

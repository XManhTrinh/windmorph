/**
 * Writes the precomputed M3 Expressive shape outlines (`src/shapes/generated`): each of
 * Compose's 35 `MaterialShapes`, normalised to the unit square, as SVG path data rounded to
 * 3 decimals. Static shapes (Avatar's, an icon container's) then cost an app only the outlines
 * it imports, with no shape engine at runtime. The files are checked in, and a unit test
 * fails when they are stale.
 */
import { MaterialShapes } from '../../src/shapes/material-shapes';
import type { Cubic } from '../../src/shapes/cubic';

/** Decimals kept in the unit square: at most 0.0005 of the size off (0.12px at 240px). */
export const SHAPE_PATH_DECIMALS = 3;

const HEADER =
  '/* Generated by @windmorph/react from src/shapes/material-shapes.ts (pnpm generate). Do not edit by hand. */\n';

/**
 * A coordinate rounded to 3 decimals, without a leading zero (`.5`, `-.25`). It is snapped
 * to 9 decimals first, as `polygonToPath` does, so the last bits of `Math.sin` / `Math.cos`
 * (which differ between engines) never tip a rounding boundary.
 */
function formatNumber(n: number): string {
  const factor = 10 ** SHAPE_PATH_DECIMALS;
  const rounded = Math.round(Number(n.toFixed(9)) * factor) / factor;
  if (rounded === 0) return '0';
  return String(rounded).replace(/^(-?)0\./, '$1.');
}

/** Numbers joined with the fewest separators SVG allows: a `-` needs no space before it. */
function joinNumbers(numbers: number[]): string {
  return numbers
    .map(formatNumber)
    .reduce((out, n, i) => (i === 0 || n.startsWith('-') ? out + n : `${out} ${n}`), '');
}

/** Compact SVG path data for a closed outline of cubics. */
export function compactPath(cubics: readonly Cubic[]): string {
  const first = cubics[0]!;
  const curves = cubics.map(
    (c) =>
      `C${joinNumbers([c.control0X, c.control0Y, c.control1X, c.control1Y, c.anchor1X, c.anchor1Y])}`,
  );
  return `M${joinNumbers([first.anchor0X, first.anchor0Y])}${curves.join('')}Z`;
}

/** `Cookie12Sided` → `cookie12SidedShape`. */
export function shapeConstantName(name: string): string {
  return `${name[0]!.toLowerCase()}${name.slice(1)}Shape`;
}

/** The outlines module: the names tuple and one constant per shape. */
export function materialShapePathsSource(): string {
  const names = Object.keys(MaterialShapes) as (keyof typeof MaterialShapes)[];
  const constants = names.map(
    (
      name,
    ) => `/** The M3 Expressive ${name} shape, precomputed (Compose \`MaterialShapes.${name}\`). */
export const ${shapeConstantName(name)}: MaterialShapePath = {
  name: '${name}',
  path: '${compactPath(MaterialShapes[name].cubics)}',
};
`,
  );
  return `${HEADER}import type { MaterialShapePath } from '../shape-path';

/** The names of the 35 M3 Expressive shapes, in Compose's \`MaterialShapes\` order. */
export const materialShapeNames = [
${names.map((name) => `  '${name}',`).join('\n')}
] as const;

/** The name of an M3 Expressive shape (Compose \`MaterialShapes\`). */
export type MaterialShapeName = (typeof materialShapeNames)[number];

${constants.join('\n')}`;
}

/** The record module: every outline by name, for galleries and pickers. */
export function materialShapePathRecordSource(): string {
  const names = Object.keys(MaterialShapes);
  return `${HEADER}import type { MaterialShapePath } from '../shape-path';
import {
${names.map((name) => `  ${shapeConstantName(name)},`).join('\n')}
  type MaterialShapeName,
} from './material-shape-paths';

/**
 * Every M3 Expressive shape's precomputed outline by name, for a shape gallery or picker.
 * Importing it costs all 35 outlines (about 11 kB gzipped once minified); to draw one shape, import its
 * constant (\`cookie12SidedShape\`) instead.
 */
export const materialShapePaths: Readonly<Record<MaterialShapeName, MaterialShapePath>> = {
${names.map((name) => `  ${name}: ${shapeConstantName(name)},`).join('\n')}
};
`;
}

/** The generated files, relative to the package root, with their contents. */
export function materialShapePathFiles(): Record<string, string> {
  return {
    'src/shapes/generated/material-shape-paths.ts': materialShapePathsSource(),
    'src/shapes/generated/material-shape-path-record.ts': materialShapePathRecordSource(),
  };
}
